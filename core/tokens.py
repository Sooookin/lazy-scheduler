        "  /* 낮 · 밤의 재료. web/sky.js 가 여기서 읽어 --surface · --text · … 를 만든다. */",
        "  " + " ".join("--lit-%s:%s;" % (k, v) for k, v in L.items()),
        "  /* 낮의 기본값. 자바스크립트가 창 요소에 덮어쓴다. */",
