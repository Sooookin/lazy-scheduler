def _mix(a, b, t):
    """두 색을 t 만큼 섞는다 (web/sky.js 의 mixc 와 같은 셈)."""
    A = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    B = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join("%02x" % int(round(x + (y - x) * t)) for x, y in zip(A, B))


