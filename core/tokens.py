def rgba(name):
    """CSS 용 rgba() 문자열."""
    rgb, a = ALPHA[name]
    return "rgba(%s,%s)" % (rgb, a)


def css_root():
    """web/style.css 의 :root 블록 안에 들어갈 줄들.

    화면이 실제로 읽는 이름만 낸다. COLOR 의 색은 알림 카드(toast.py) · 트레이 · 휴대폰(Theme.kt)이 쓴다."""
