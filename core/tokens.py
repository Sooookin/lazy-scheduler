def rgba_tuple(name):
    """PIL 용 (r, g, b, a). CSS 의 rgba() 와 같은 값이 나온다."""
    rgb, a = ALPHA[name]
    r, g, b = (int(v) for v in rgb.split(","))
    return (r, g, b, int(round(float(a) * 255)))

